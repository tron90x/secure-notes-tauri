function applyI18n() {
  if (document.documentElement) document.documentElement.lang = LANG;
  document.title = t("app_title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    // Bouton corbeille : préserver le compteur <span id="trashCount">
    if (el.id === "showTrashBtn") {
      const n = document.getElementById("trashCount")?.textContent ?? "0";
      el.innerHTML = `${t(el.dataset.i18n)} (<span id="trashCount">${n}</span>)`;
      return;
    }
    el.innerHTML = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.querySelectorAll("[data-lang-btn]").forEach((b) => {
    b.classList.toggle("primary", b.dataset.langBtn === LANG);
    b.classList.toggle("ghost", b.dataset.langBtn !== LANG);
  });
}

function setLang(l) {
  LANG = STRINGS[l] ? l : "fr";
  try { localStorage.setItem("sn_lang", LANG); } catch (e) {}
  applyI18n();
}
