function localizeError(error) {
  const message = String(error?.message || error);
  if (LANG !== "kab") return message;
  if (Object.hasOwn(KAB_ERRORS, message)) return KAB_ERRORS[message];
  const prefix = "Brouillon conservé — enregistrement de la note impossible : ";
  if (message.startsWith(prefix)) return "Arewway yettwaḥrez — asekles n tezmilt ur yeddi ara: " + localizeError(message.slice(prefix.length));
  if (message.startsWith("Fichier de note absent : ")) return "Afaylu n tezmilt ulac-it: " + message.slice("Fichier de note absent : ".length);
  const utf8 = message.match(/^Le fichier (.+) n'est pas en UTF-8$/s);
  if (utf8) return `Afaylu ${utf8[1]} mačči s UTF-8`;
  return message; // Les diagnostics système restent intacts.
}

